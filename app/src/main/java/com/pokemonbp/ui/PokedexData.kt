data class PokedexEntry(
    val id: Int,
    val name: String,       // English
    val nameDE: String,     // German
    val types: List<PokemonType>,
    val isMega: Boolean = false,
    val spriteUrl: String? = null,  // legacy URL field
    val spriteId: Int = id          // actual sprite ID (differs from id for Megas)
) {
    fun displayName() = "$nameDE / $name"
    fun spriteUrl(): String = spriteUrl
        ?: "https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/$spriteId.png"
}

